// iOS version stamping. client/package.json "version" is the single
// source for MARKETING_VERSION (CFBundleShortVersionString). The build
// number (CURRENT_PROJECT_VERSION / CFBundleVersion) is never committed:
// it comes from OC_IOS_BUILD_NUMBER at build time (for example the CI run
// number or a UTC timestamp) and defaults to 1 for local dev builds.

const SEMVER = /^\d+\.\d+\.\d+$/
const BUILD = /^[1-9]\d{0,17}$/

export const BUILD_NUMBER_ENV = 'OC_IOS_BUILD_NUMBER'

export function marketingVersion(pkgVersion) {
  const v = String(pkgVersion ?? '').trim()
  if (!SEMVER.test(v)) {
    throw new Error(`client/package.json version must be plain semver (x.y.z), got "${v}"`)
  }
  return v
}

export function buildNumber(env = process.env) {
  const raw = env?.[BUILD_NUMBER_ENV]
  if (raw === undefined || String(raw).trim() === '') return '1'
  const v = String(raw).trim()
  if (!BUILD.test(v)) {
    throw new Error(`${BUILD_NUMBER_ENV} must be a positive integer, got "${v}"`)
  }
  return v
}

export function versionXcconfig(pkgVersion, env = process.env) {
  return [
    '// Generated by scripts/ios-sync.mjs from client/package.json.',
    `// Do not edit or commit build-number bumps; set ${BUILD_NUMBER_ENV} at build time.`,
    `MARKETING_VERSION = ${marketingVersion(pkgVersion)}`,
    `CURRENT_PROJECT_VERSION = ${buildNumber(env)}`,
    '',
  ].join('\n')
}
